function writeSubject(sid, rows) {
  const combined = rows;
  const { ru, kk } = splitData(combined);
  writeFileSync(join(DATA, `${sid}.json`), JSON.stringify(combined));
  writeFileSync(join(DATA, `${sid}.ru.json`), JSON.stringify(ru));
  writeFileSync(join(DATA, `${sid}.kk.json`), JSON.stringify(kk));
  writeFileSync(join(DATA, `${sid}.meta.json`), JSON.stringify(computeMeta(combined)));
  return { total: combined.length, ru: ru.length };
}

function countTypes(rows) {
  const t = {};
  for (const q of rows) t[q.type || 'single'] = (t[q.type || 'single'] || 0) + 1;
  return t;
}

