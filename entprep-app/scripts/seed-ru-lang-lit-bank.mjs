function seedLiterature() {
  const path = join(DATA, 'literature_russian.json');
  const rows = JSON.parse(readFileSync(path, 'utf8'));
  const types = countTypes(rows);
  if ((types.matching || 0) >= 40) {
    console.log('literature_russian: matching already ≥40, skip typed append');
    return writeSubject('literature_russian', rows);
  }
  const added = [...expandLitMatching(), ...expandLitMultiple(), ...expandLitContext()];
  const next = rows.concat(added);
  console.log('literature_russian: appended', added.length, 'typed questions');
  return writeSubject('literature_russian', next);
}

